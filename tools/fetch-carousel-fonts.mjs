/**
 * Vendors subset fonts for the script carousel.
 *
 * Google Fonts cuts a face down to the glyphs of a given string, keeping the
 * shaping tables those glyphs need, so each file here is a few kilobytes and
 * renders exactly one phrase correctly. Run once; the output is committed and
 * served from this origin, so nothing is fetched at runtime.
 */
import fs from 'node:fs';
import path from 'node:path';
import { CAROUSEL } from '../apps/web/src/kiosk/carousel.ts';

const OUT = 'apps/web/public/fonts/carousel';
const UA = 'Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0.0.0 Safari/537.36';
fs.mkdirSync(OUT, { recursive: true });

// The font host occasionally drops a connection; retry rather than fail the run.
async function get(url, attempts = 4) {
  let last;
  for (let i = 0; i < attempts; i++) {
    try {
      const res = await fetch(url, { headers: { 'User-Agent': UA }, signal: AbortSignal.timeout(20000) });
      if (!res.ok) throw new Error(`${res.status} ${url}`);
      return res;
    } catch (e) {
      last = e;
      await new Promise((r) => setTimeout(r, 1500 * (i + 1)));
    }
  }
  throw last;
}

const faces = [];
for (const p of CAROUSEL) {
  if (p.source === null) continue;
  const family = p.source.replace(/ /g, '+');
  const url = `https://fonts.googleapis.com/css2?family=${family}&text=${encodeURIComponent(p.text)}`;
  const css = await (await get(url)).text();
  const src = css.match(/url\((https:[^)]+)\)/)?.[1];
  if (!src) throw new Error(`no font returned for ${p.source}: ${css.slice(0, 160)}`);
  const bytes = Buffer.from(await (await get(src)).arrayBuffer());
  const file = `${p.script}.woff2`;
  fs.writeFileSync(path.join(OUT, file), bytes);
  faces.push(`@font-face {\n  font-family: "${p.family}";\n  src: url("/fonts/carousel/${file}") format("woff2");\n  font-display: block;\n}`);
  console.log(`  ${String(bytes.length).padStart(6)} bytes  ${p.script.padEnd(10)} ${p.text}`);
}
fs.writeFileSync(
  'apps/web/src/kiosk/carousel-fonts.css',
  `/* Generated by tools/fetch-carousel-fonts.mjs. Subsets: one phrase each. */\n\n${faces.join('\n\n')}\n`,
);
const total = fs.readdirSync(OUT).reduce((n, f) => n + fs.statSync(path.join(OUT, f)).size, 0);
console.log(`  ${String(total).padStart(6)} bytes  total for ${faces.length} scripts`);
